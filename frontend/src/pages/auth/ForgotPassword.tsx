import React, { useState } from 'react';
import { Link } from 'react-router-dom';
import { Bus, KeyRound, ArrowLeft } from 'lucide-react';

export const ForgotPassword: React.FC = () => {
  const [email, setEmail] = useState('');
  const [submitted, setSubmitted] = useState(false);

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    setSubmitted(true);
  };

  return (
    <div className="min-h-screen flex items-center justify-center bg-base p-6 select-none">
      <div className="w-full max-w-md bg-surface border border-border rounded-2xl shadow-card p-8 md:p-10 space-y-6">
        <div className="flex items-center space-x-3">
          <div className="w-10 h-10 rounded-xl bg-primary text-white flex items-center justify-center">
            <Bus className="w-5 h-5 text-white" />
          </div>
          <div>
            <h1 className="text-xl font-bold text-textPrimary">Password Recovery</h1>
            <p className="text-xs text-textSecondary">Secure token-based credential reset</p>
          </div>
        </div>

        {submitted ? (
          <div className="space-y-4">
            <div className="p-4 bg-emerald-50 text-emerald-800 rounded-lg border border-emerald-200 text-sm">
              <h2 className="font-bold flex items-center text-sm">
                <KeyRound className="w-4 h-4 mr-1.5 text-emerald-600" />
                Reset Instructions Prepared
              </h2>
              <p className="mt-1 text-xs text-emerald-700 leading-relaxed">
                In accordance with transit air-gap security guidelines, reset tokens are generated by the
                system administrator. If an account exists for <span className="font-semibold">{email}</span>,
                contact the admin at <span className="font-mono font-semibold">admin@busarrival.local</span> to
                obtain a single-use authorization token.
              </p>
            </div>
            <Link
              to="/login"
              className="inline-flex items-center justify-center w-full h-10 bg-subtle hover:bg-slate-100 border border-border rounded-input text-xs font-semibold text-textPrimary transition-colors"
            >
              <ArrowLeft className="w-4 h-4 mr-1.5" />
              Return to Sign In
            </Link>
          </div>
        ) : (
          <form onSubmit={handleSubmit} className="space-y-4">
            <p className="text-xs text-textSecondary leading-relaxed">
              Enter your registered transit email address to receive authorization guidance.
            </p>
            <div>
              <label className="block text-xs font-semibold text-textSecondary uppercase tracking-wider mb-1.5">
                Email Address
              </label>
              <input
                type="email"
                required
                value={email}
                onChange={(e) => setEmail(e.target.value)}
                placeholder="name@transit.local"
                className="w-full h-10 px-3.5 text-sm bg-subtle border border-border rounded-input text-textPrimary focus:ring-2 focus:ring-primary focus:outline-none"
              />
            </div>

            <button
              type="submit"
              className="w-full h-11 bg-primary hover:bg-primary-hover text-white rounded-input font-semibold text-sm transition-colors shadow-sm cursor-pointer"
            >
              Request Reset Token
            </button>

            <div className="text-center pt-2">
              <Link to="/login" className="text-xs text-textSecondary hover:text-primary inline-flex items-center">
                <ArrowLeft className="w-3.5 h-3.5 mr-1" />
                Back to Sign In
              </Link>
            </div>
          </form>
        )}
      </div>
    </div>
  );
};
